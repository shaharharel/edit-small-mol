#!/usr/bin/env python3
"""Restructure covalentformer_report.html and add two blocks of new material.

WHY THIS EDITS THE HTML AND NOT mk_report.py
--------------------------------------------
The report was originally generated by mk_report.py, but the live HTML has since DIVERGED from
it: the big results table (section "Current results"), its chemist columns and every later
revision exist only in the HTML. Re-running mk_report.py would delete all of that. So the HTML is
now the source of truth and this script operates on it directly, idempotently, and asserts before
every splice.

WHAT IT DOES
  1. Moves the labelled-dataset section to position 2, ahead of the results table.
  2. Appends 5 g3 TRAINING examples to that section (the existing 10 are rung-3 showcase rows).
  3. Builds a new "Generation sample" section: 3 held-out test pairs answered by ChemDFM-14B
     base, g3 and g3+g4, followed by the existing ZAP70/mol1 material demoted under it.
  4. Renumbers every <h2> sn badge to the new order.

Molecule art matches the existing lbl-t tables: 330x230 SVG, changed atoms in #FFB74C, found by
MCS against the other side of the pair.
"""
import json, os, re, sys
from rdkit import Chem, RDLogger
from rdkit.Chem import rdFMCS, rdDepictor
from rdkit.Chem.Draw import rdMolDraw2D
RDLogger.DisableLog('rdApp.*')

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
REPORT = os.path.join(HERE, 'covalentformer_report.html')
EVIDENCE = os.path.join(ROOT, 'data/pdb_mirror/v7_evidence.jsonl')
G3_TRAIN = os.path.join(HERE, 'v6/sft_out_g3/sft_pocket.jsonl')
SCRATCH = ('/private/tmp/claude-501/-Users-shaharharel-Documents-github-edit-small-mol/'
           'a64ce54a-c2cc-42bc-bc54-bfe1ad41d081/scratchpad')

ARMS = [('ChemDFM-14B base', SCRATCH + '/alltab/sft_runs/zeroshot_chemdfm_bench/generations.jsonl'),
        ('ChemDFM-14B g3', os.path.join(HERE, 'v6/sft_2k/chemdfm_pocket_g3/generations.jsonl')),
        ('ChemDFM-14B g3+g4', SCRATCH + '/g3g4res/chemdfm/generations.jsonl')]

# Three held-out pairs every ChemDFM arm answered, chosen to show the base model's three distinct
# failure modes rather than three instances of one.
# Chosen by blind audit, not by eye. Three medicinal-chemistry reviewers scored 12 candidate pairs
# x 3 arms = 36 proposals with arm identity hidden (letters reshuffled per pair); these are the
# only three pairs all three reviewers judged a fair illustration AND would publish, and all three
# agreed on the best slot in each. The three pairs shown here previously -- 6PGE, 5OIW, 6G9H --
# were rejected unanimously: 6PGE and 6G9H as degenerate (the two trained arms give the same
# molecule with the same argument), and in 6G9H both trained arms additionally credit a retained
# tert-butyl's contacts to the oxane ring they edited.
SHOWCASE = [
    ('7KXD Z7G->Z7H',
     'the untrained arm returns the input unchanged while announcing an edit'),
    ('8FAV LKY->XNR',
     'the untrained arm is the only accurate slot here -- both trained arms misattribute'),
    ('7I9F A1B6G->A1B6H',
     'a clean trained slot, against one that makes two edits and calls it one'),
]

# Five g3 training rows. Picked for recognisable targets and a chair sentence that names a measured
# distance, which is what rung 3 is supposed to teach.
# Chosen by unanimous verdict of three independent medicinal-chemistry reviewers auditing 18
# candidates against their own contact tables (panel_g3_exemplars/, 2026-10-19). Each of these
# cleared all five fields from all three reviewers. The three rows replaced -- 8AI0 M79->O4I,
# 7B9Z T58->R3B and 9Q66 A1CQP->A1CQZ -- failed unanimously on edit_described_correctly: an
# unflagged para-chlorine, a meta->para methoxy translocation in the macrocyclic tether, and a
# silent one-carbon homologation hidden behind the word "aromatises". 9QDB is kept deliberately:
# it is the only sentence in the panel that discloses its own stereocentre inversion.
G3_PICKS = ['6EAA J1V->J2D', '6P6G LUP->O41', '8AV8 O4R->NQU',
            '8P9L XA3->X9U', '9QDB A1I5Y->A1I53']

ORANGE = (1.0, 0.718, 0.298)   # #FFB74C


def esc(s):
    return (str(s).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))


def changed_atoms(mol, other):
    """Atoms of `mol` absent from the maximum common substructure with `other`."""
    if mol is None or other is None:
        return []
    try:
        res = rdFMCS.FindMCS([mol, other], timeout=10,
                             atomCompare=rdFMCS.AtomCompare.CompareElements,
                             bondCompare=rdFMCS.BondCompare.CompareAny,
                             ringMatchesRingOnly=True, completeRingsOnly=False)
        if not res or not res.smartsString:
            return []
        patt = Chem.MolFromSmarts(res.smartsString)
        match = mol.GetSubstructMatch(patt) if patt else ()
        return [a.GetIdx() for a in mol.GetAtoms() if a.GetIdx() not in set(match)]
    except Exception:
        return []


def svg(smiles, other_smiles, w=330, h=230):
    m = Chem.MolFromSmiles(smiles) if smiles else None
    if m is None:
        return '<div class="pend">unparseable</div>'
    o = Chem.MolFromSmiles(other_smiles) if other_smiles else None
    hi = changed_atoms(m, o)
    rdDepictor.Compute2DCoords(m)
    d = rdMolDraw2D.MolDraw2DSVG(w, h)
    d.drawOptions().clearBackground = True
    rdMolDraw2D.PrepareAndDrawMolecule(
        d, m, highlightAtoms=hi, highlightAtomColors={i: ORANGE for i in hi})
    d.FinishDrawing()
    return d.GetDrawingText().replace('<?xml version=\'1.0\' encoding=\'iso-8859-1\'?>\n', '')


def gen_smiles(r):
    """The generated SMILES, or None. The field can hold the STRING 'None', which is truthy."""
    for k in ('gen_smiles_canonical', 'gen_smiles'):
        v = r.get(k)
        if isinstance(v, str) and v.strip() and v.strip() != 'None':
            return v.strip()
    return None


def canon(x):
    m = Chem.MolFromSmiles(x) if x else None
    return Chem.MolToSmiles(m) if m else None


def lbl_table(headers, rows):
    h = ''.join('<th>%s</th>' % x for x in headers)
    b = ''.join('<tr>' + ''.join(cells) + '</tr>' for cells in rows)
    return ('<div class="tw"><table class="lbl-t"><thead><tr>%s</tr></thead>'
            '<tbody>%s</tbody></table></div>' % (h, b))


def build_g3_training_block():
    rows = {}
    for line in open(G3_TRAIN):
        r = json.loads(line)
        if r['split'] == 'train' and r['pair'] in G3_PICKS:
            rows[r['pair']] = r
    missing = [p for p in G3_PICKS if p not in rows]
    assert not missing, 'g3 training pairs not found: %s' % missing
    out = []
    for p in G3_PICKS:
        r = rows[p]
        meta = ('<div class="lbl-meta">PDB %s &middot; %s &middot; pair <code>%s</code> &middot; '
                '%s atom rows &middot; %s table residues &middot; chair verdict '
                '<code>%s</code></div>'
                % (esc(r.get('pdb')), esc(r.get('target')), esc(r['pair']),
                   esc(r.get('n_atom_rows')), len(r.get('table_residues') or []),
                   esc(r.get('verdict'))))
        out.append([
            '<td class="mol"><div class="lbl-hd">input</div>%s</td>'
            % svg(r['input_smiles'], r['analogue_smiles']),
            '<td class="mol"><div class="lbl-hd">analogue</div>%s</td>'
            % svg(r['analogue_smiles'], r['input_smiles']),
            '<td><div class="lbl-hd">chair sentence &mdash; the training target</div>'
            '<div class="lbl-rsn">%s</div>%s</td>'
            % (esc(r.get('reference_sentence')), meta)])
    lede = ('<h3>Five rows of g3 training data</h3>'
            '<p class="lede">These are <b>training</b> rows, not showcase rows &mdash; five of the '
            '2,326 in <code>sft_out_g3</code>, drawn from the '
            '<code>g3_v2_input_anchored_envelope</code> labelling pass. The third column is '
            'literally the completion the model is fine-tuned to emit: one sentence, anchored on '
            'the <i>input</i> crystal’s measured geometry, naming what the edit gives up and '
            'what it keeps. Every row shown carries a chair verdict of <code>ADOPT</code>. Orange '
            'marks the atoms that changed.</p>')
    return lede + lbl_table(('input (hit)', 'output (analogue)',
                             'chair sentence (training target)'), out)


def build_generation_block():
    inp = {}
    for line in open(EVIDENCE):
        r = json.loads(line)
        inp[r['pair']] = (r['MODEL_INPUT'] or {}).get('input_smiles')
    data = {}
    for name, path in ARMS:
        assert os.path.exists(path), 'missing generations: %s' % path
        data[name] = {r['pair']: r for r in (json.loads(l) for l in open(path))}
    rows = []
    for pair, why in SHOWCASE:
        ref = data['ChemDFM-14B g3'][pair].get('reference_smiles')
        tgt = data['ChemDFM-14B g3'][pair].get('target')
        rows.append(['<td class="mol" colspan="3"><div class="lbl-hd">held-out pair '
                     '<code>%s</code> &middot; %s &middot; %s</div>'
                     '<div class="lbl-meta">input ligand, with the crystallographic analogue '
                     'for reference only &mdash; the models were never asked to reproduce '
                     'it</div></td>' % (esc(pair), esc(tgt), esc(why))])
        for name, _ in ARMS:
            r = data[name][pair]
            g = gen_smiles(r)
            echo = canon(g) is not None and canon(g) == canon(inp[pair])
            badge = ' &middot; <b>echo of the input</b>' if echo else ''
            rows.append([
                '<td class="mol"><div class="lbl-hd">input</div>%s</td>'
                % svg(inp[pair], g),
                '<td class="mol"><div class="lbl-hd">%s%s</div>%s</td>'
                % (esc(name), badge, svg(g, inp[pair])),
                '<td><div class="lbl-hd">Model reasoning</div>'
                '<div class="lbl-rsn">%s</div></td>'
                % esc((r.get('gen_sentence') or '').strip() or '(no sentence)')])
    lede = ('<h3>Held-out test pairs &mdash; the same three pairs, three ChemDFM arms</h3>'
            '<p class="lede">Three pairs from the 262-row held-out set that <b>all three</b> arms '
            'answered with a parseable molecule and a sentence &mdash; only 27 of 262 pairs clear '
            'that bar for all three, because the base model clears it just 31 times on its own. '
            'Each block shows the input ligand, then what each arm proposed and the sentence it '
            'wrote. Nothing is cherry-picked in the arms’ favour: the three pairs were chosen '
            'to show the base model’s three distinct failure modes. Orange marks the atoms '
            'that differ from the other molecule in the row.</p>')
    note = ('<p class="tnote">What to look for. The base model fails in three ways that the '
            'aggregate columns flatten into one number: it answers in <b>Chinese</b> on the first '
            'pair, it <b>hands back its own input</b> unchanged on the second, and on the third it '
            'writes fluent English that names residues but <b>cites no measured distance at all</b> '
            '&mdash; the behaviour its 0.161 echo rate and 11.8% validity describe from the '
            'outside. Both trained arms instead name a specific distance and say what is given up '
            'and what is kept, which is the shape of the chair sentence they were trained on. They '
            'are not thereby correct: on the third pair g3 and g3+g4 propose the <i>same</i> '
            'molecule and attribute it to two different residues, and that disagreement is exactly '
            'the attribution failure the chemist panels measure.</p>')
    return lede + lbl_table(('input (hit)', 'generated analogue', 'model output'), rows) + note


def main():
    s = open(REPORT).read()
    if 'id="gen-sample-chemdfm"' in s:
        print('already applied; nothing to do')
        return 0

    hs = [(m.start(), m.end(), m.group(1), m.group(2)) for m in
          re.finditer(r'<h2><span class="sn">(\d+)</span>(.*?)</h2>', s)]
    assert len(hs) == 10, 'expected 10 h2 sections, found %d' % len(hs)
    off = {re.sub('<[^>]+>', '', t)[:28]: (a, b) for a, b, n, t in hs}

    def start(key):
        for k, v in off.items():
            if k.startswith(key):
                return v[0]
        raise KeyError(key)

    a_tbl = start('Current results')
    a_phase = start('The three training phases')
    a_lbl = start('Labelled dataset')
    a_zap = start('Generation sample')

    HEAD = s[:a_tbl]                 # section 1
    TBL = s[a_tbl:a_phase]           # results table
    MID = s[a_phase:a_lbl]           # training phases .. compute note
    LBL = s[a_lbl:a_zap]             # labelled dataset
    ZAP = s[a_zap:]                  # ZAP70 / mol1

    # 2. append the g3 training rows to the labelled-dataset section
    LBL = LBL + '\n' + build_g3_training_block() + '\n'

    # 3. new Generation sample section: test pairs, then the ZAP70 material demoted to h3
    zap_h2 = re.match(r'<h2><span class="sn">\d+</span>(.*?)</h2>', ZAP)
    assert zap_h2, 'ZAP70 section does not start with its h2'
    ZAP_BODY = ZAP[zap_h2.end():]
    GEN = ('<h2><span class="sn">4</span>Generation sample</h2>\n'
           '<div id="gen-sample-chemdfm"></div>\n'
           + build_generation_block()
           + '\n<h3>ZAP70, mol1 &mdash; the v4b and v5 arms</h3>\n'
           + '<p class="lede">The block below predates the ChemDFM arms and shows the earlier '
             'v4b/v5 models on ZAP70 mol1. The three arms above have <b>not</b> been run on mol1; '
             'that needs the A100 restarted and each adapter sampled against the mol1 prompt.</p>\n'
           + ZAP_BODY)

    out = HEAD + LBL + TBL + GEN + MID

    # 4. renumber the h2 badges in document order
    seq = iter(range(1, 11))
    out = re.sub(r'(<h2><span class="sn">)\d+(</span>)',
                 lambda m: '%s%d%s' % (m.group(1), next(seq), m.group(2)), out)

    order = [re.sub('<[^>]+>', '', m.group(2))[:46] for m in
             re.finditer(r'<h2><span class="sn">(\d+)</span>(.*?)</h2>', out)]
    assert len(order) == 10, len(order)
    open(REPORT, 'w').write(out)
    for i, t in enumerate(order, 1):
        print('%2d  %s' % (i, t))
    return 0


if __name__ == '__main__':
    sys.exit(main())
