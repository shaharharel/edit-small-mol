#!/usr/bin/env python3
"""Safe merge of FiLM-scored 215K survivors back into the full 317K Tier 4 set.

Key correctness guarantees:
  1. Join key is the (smiles, method) TUPLE — not bare SMILES — to defend
     against the same canonical SMILES being generated by multiple cohorts.
  2. Sanity check: number of rows getting FiLM populated must equal the
     number of rows in the FiLM output CSV.
  3. Spot-check: pick 10 random rows from the FiLM CSV; verify the
     (smiles, method) tuple appears exactly once in the merged output AND
     the pIC50_method value matches.
  4. Distribution sanity: pIC50 mean across cohorts should be in [4, 9]
     (anchors are kinase pIC50 values 4-10).

Inputs:
  full_csv  = .../tier4_overnight_bulk.phase1_physchem.csv.with_flag.csv (317K rows)
  film_csv  = .../tier4_overnight_bulk.filter1_with_film.csv (215K rows + FiLM cols)
Output:
  tier4_overnight_bulk.csv (317K rows, FiLM cols populated on survivors only)
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd

PROJECT = Path("/Users/shaharharel/Documents/github/edit-small-mol")
RES = PROJECT / "results/paper_evaluation"
FULL_CSV = RES / "tier4_overnight_bulk.phase1_physchem.csv.with_flag.csv"
FILM_CSV = RES / "tier4_overnight_bulk.filter1_with_film.csv"
OUT_CSV = RES / "tier4_overnight_bulk.csv"

FILM_COLS = ["pIC50_method", "pIC50_film", "pIC50_mean", "pIC50_std",
             "delta_vs_mol1", "direct_delta_from_mol1",
             "anchor_wins", "anchor_wins_ge7"]


def main():
    print("Loading inputs...")
    full = pd.read_csv(FULL_CSV)
    film = pd.read_csv(FILM_CSV)
    print(f"  full: {len(full):,} rows  ·  film: {len(film):,} rows")

    # Check: every FiLM row has its (smiles, method) tuple present in full
    full_keys = set(zip(full["smiles"], full["method"]))
    film_keys = set(zip(film["smiles"], film["method"]))
    missing = film_keys - full_keys
    if missing:
        print(f"  ⚠ {len(missing)} (smiles, method) pairs in FILM not in FULL — first 3: {list(missing)[:3]}")
    else:
        print(f"  ✓ all {len(film_keys):,} (smiles, method) keys in FILM also in FULL")

    # Drop pIC50_* / delta_* columns from full (all NaN) before merge to avoid suffix collisions
    full_clean = full.drop(columns=[c for c in FILM_COLS if c in full.columns], errors="ignore")

    # Dedup film by (smiles, method) — duplicates are cross-seed sampling artifacts.
    # The deterministic FiLM model gives the same score for a given SMILES every time,
    # so keep="first" is exact (NOT lossy).
    film_dedup = film.drop_duplicates(subset=["smiles", "method"], keep="first").reset_index(drop=True)
    print(f"  film deduped by (smiles, method): {len(film):,} → {len(film_dedup):,}")

    # Sanity: dedup preserves score (no two rows with same key + different score)
    score_check = film.groupby(["smiles", "method"])["pIC50_method"].nunique().max()
    assert score_check == 1, f"BLOCKER: same (smiles, method) has differing FiLM scores (max distinct = {score_check})"
    print(f"  ✓ score consistency: all (smiles, method) duplicates have identical FiLM scores")

    # Merge on (smiles, method) — many-to-one: full may have duplicates (carry through), film is unique now.
    film_keep = film_dedup[["smiles", "method"] + FILM_COLS].copy()
    out = full_clean.merge(film_keep, on=["smiles", "method"], how="left", validate="many_to_one")
    print(f"  merged: {len(out):,} rows  ·  validate=many_to_one passed")
    n_pop = out["pIC50_method"].notna().sum()
    print(f"  FiLM populated: {n_pop:,}  (expected {len(film):,} from film CSV, {len(film_dedup):,} unique)")

    # Spot-check: 10 random film rows must match in merged output
    import random
    random.seed(0)
    idxs = random.sample(range(len(film)), 10)
    print("\nSpot-check (10 random rows):")
    all_ok = True
    for i in idxs:
        r = film.iloc[i]
        match = out[(out["smiles"] == r["smiles"]) & (out["method"] == r["method"])]
        if len(match) == 0:
            print(f"  ✗ idx {i}: NO matches — merge dropped this row")
            all_ok = False
            continue
        # match.len > 1 is fine: full had within-cohort dups; all should now share the same FiLM
        scores = match["pIC50_method"].unique()
        ok = (len(scores) == 1) and (abs(scores[0] - r["pIC50_method"]) < 1e-4)
        marker = "✓" if ok else "✗"
        print(f"  {marker} idx {i}  match_count={len(match):>2} method={r['method'][:40]:<40} film={r['pIC50_method']:.3f}  merged={scores[0]:.3f}")
        all_ok &= ok
    if not all_ok:
        raise RuntimeError("Spot-check FAILED — merge produced wrong values")
    print("  ✓ all 10 spot-checks passed")

    # Distribution sanity
    p = out["pIC50_method"].dropna()
    if len(p) > 0:
        print(f"\npIC50 distribution: min={p.min():.2f}  p10={p.quantile(0.1):.2f}  median={p.median():.2f}  p90={p.quantile(0.9):.2f}  max={p.max():.2f}")
        if not (4.0 < p.median() < 9.0):
            print(f"  ⚠ pIC50 median {p.median():.2f} outside [4, 9] — possible model issue")
    print("\nPer-method pIC50 summary:")
    grp = out.dropna(subset=["pIC50_method"]).groupby("method")["pIC50_method"].agg(["count","mean","std","min","max"]).round(3)
    print(grp.to_string())

    out.to_csv(OUT_CSV, index=False)
    print(f"\n→ {OUT_CSV}  ({OUT_CSV.stat().st_size/1e6:.1f} MB)")


if __name__ == "__main__":
    main()
